async (page) => {
  const results = []
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  const root = 'http://127.0.0.1:5173/#/pages/'
  const click = (name) => page.getByRole('button', { name, exact: true }).click()
  const role = async (name) => {
    await page.goto(root + 'auth/role')
    await page.reload()
    await click(
      name === 'elder'
        ? '我是长辈 看看家人，动动脑 和忆伴说说话'
        : '我是家属 留下家庭回忆 关心家人的每一天',
    )
  }
  await role('elder')
  await page.goto(root + 'account/binding')
  await page.getByText('一个家，彼此相伴', { exact: true }).waitFor()
  if (await page.getByRole('button', { name: '恢复演示家庭绑定', exact: true }).count()) {
    await click('恢复演示家庭绑定')
    await page.getByText('演示家庭已绑定', { exact: true }).waitFor()
  }
  await page.goto(root + 'account/privacy')
  const editToggle = page.getByRole('switch').filter({ hasText: '允许家属编辑家庭记忆' })
  if ((await editToggle.getAttribute('aria-checked')) === 'false') await editToggle.click()
  await role('family')
  await page.getByRole('navigation').getByRole('button', { name: '家庭互动', exact: true }).click()
  await click('留一句问候')
  await click('留下这句问候')
  await page.getByRole('status').filter({ hasText: '请填写留言' }).waitFor()
  await page.getByRole('textbox', { name: '想对家人说的话' }).fill('妈妈，周末我们一起去公园看花。')
  await click('春节家庭合影')
  await click('留下这句问候')
  await page.getByText('妈妈，周末我们一起去公园看花。', { exact: true }).first().waitFor()
  results.push('family text and photo message')
  await click('生日与重要日期')
  await click('添加日期')
  await page.getByRole('textbox', { name: '日子名称' }).fill('一起团聚的日子')
  await page.getByRole('textbox', { name: '日期（YYYY-MM-DD）' }).fill('2026-12-20')
  await page.getByRole('textbox', { name: '一句备注' }).fill('拍一张新的全家福。')
  await click('保存重要日期')
  await page.getByText('一起团聚的日子', { exact: true }).waitFor()
  await page.reload()
  const dateCard = page.locator('.date-card').filter({ hasText: '一起团聚的日子' })
  await dateCard.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByRole('textbox', { name: '一句备注' }).fill('一起吃饭，再拍一张新的全家福。')
  await click('保存重要日期')
  await page.getByText('一起吃饭，再拍一张新的全家福。', { exact: true }).waitFor()
  await dateCard.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByText('确认', { exact: true }).click()
  if (await page.getByText('一起团聚的日子', { exact: true }).count())
    throw new Error('date not removed')
  results.push('important date create, edit, persist and delete')
  await page.goto(root + 'account/profile')
  await page.getByRole('textbox', { name: '姓名', exact: true }).fill('小明家属')
  await click('保存个人资料')
  await page.goto(root + 'account/index')
  await page.getByText('小明家属', { exact: true }).waitFor()
  results.push('family profile persistence')
  await role('elder')
  await page.goto(root + 'messages/index')
  await page.getByText('妈妈，周末我们一起去公园看花。', { exact: true }).first().waitFor()
  await page.getByText('已读', { exact: true }).first().waitFor()
  results.push('elder receives and reads family message')
  await page.goto(root + 'account/privacy')
  await page.getByRole('switch').filter({ hasText: '允许家属编辑家庭记忆' }).click()
  await role('family')
  await page.goto(root + 'family/person-edit')
  await page
    .getByRole('button', { name: '保存到家庭', exact: true })
    .isDisabled()
    .then((v) => {
      if (!v) throw new Error('unauthorized edit enabled')
    })
  results.push('elder controls family edit permission')
  await role('elder')
  await page.goto(root + 'account/privacy')
  await page.getByRole('switch').filter({ hasText: '允许家属编辑家庭记忆' }).click()
  await page.goto(root + 'account/binding')
  const invite = await page.locator('.invite-code').textContent()
  await click('暂停这个演示家庭的绑定')
  await page.getByText('确认', { exact: true }).click()
  await role('family')
  await page.goto(root + 'family/interaction')
  await page.getByText('家庭绑定已暂停', { exact: true }).waitFor()
  await click('查看家庭绑定')
  await page.getByRole('textbox', { name: '长辈提供的演示邀请码' }).fill('000000')
  await click('确认演示绑定')
  await page.getByRole('status').filter({ hasText: '演示邀请码不匹配' }).waitFor()
  await page.getByRole('textbox', { name: '长辈提供的演示邀请码' }).fill(invite.trim())
  await page.getByRole('switch').filter({ hasText: '我了解这是同一设备的演示绑定' }).click()
  await page.waitForFunction(()=>document.querySelector('[role=switch]')?.getAttribute('aria-checked')==='true')
  await click('确认演示绑定')
  await page.getByText('演示家庭已绑定', { exact: true }).waitFor()
  results.push('local invite validation, unbind and rebind')
  await page.goto(root + 'account/notifications')
  const toggle = page.getByRole('switch').filter({ hasText: '重要日期提醒' })
  const old = await toggle.getAttribute('aria-checked')
  await toggle.click()
  await page.reload()
  await page
    .getByRole('switch')
    .filter({ hasText: '重要日期提醒' })
    .getAttribute('aria-checked')
    .then((v) => {
      if (v === old) throw new Error('notification preference not persisted')
    })
  results.push('notification preference persistence')
  if (errors.length) throw new Error(errors.join(';'))
  return { module: 'family', passed: results, errors }
}
