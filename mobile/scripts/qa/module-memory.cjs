  await title('故事详情')
  await page.getByText('这个故事的照片还没有添加。', { exact: true }).waitFor()
  await page.getByRole('button', { name: '女儿 测试家人', exact: true }).waitFor()
  results.push('story create and person link')
  await page.goto(root + 'family/media-add')
  await click('使用示例家庭照片')
