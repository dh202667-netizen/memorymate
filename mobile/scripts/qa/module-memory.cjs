  await page.getByRole('textbox', { name: '故事标题', exact: true }).fill('一起逛公园的下午')
  await page
    .getByRole('textbox', { name: '一句话简介', exact: true })
    .fill('和女儿一起在公园看花。')
  await page
    .getByRole('textbox', { name: '故事内容', exact: true })
    .fill('那天下午，我们一起走到公园。妈妈说，花开得真好看。大家拍了一张合影，约好下次再来。')
