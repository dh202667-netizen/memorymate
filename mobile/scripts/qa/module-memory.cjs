  await page.getByRole('textbox', { name: '与长辈的关系', exact: true }).fill('女儿')
  await page.getByRole('textbox', { name: '人物介绍', exact: true }).fill('喜欢陪妈妈看家庭相册。')
  await click('保存到家庭')
