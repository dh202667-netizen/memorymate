  await click('女儿 测试家人')
  await title('人物详情')
  await click('编辑人物资料')
  await page
    .getByRole('textbox', { name: '人物介绍', exact: true })
    .fill('周末一起散步，也一起看家庭相册。')
  await click('保存到家庭')
  await title('人物详情')
  await page.getByText('周末一起散步，也一起看家庭相册。', { exact: true }).waitFor()
  results.push('person create and edit')
  await page.reload()
  await page.getByText('测试家人', { exact: true }).waitFor()
  results.push('person persistence')
